const courseRoot = 'https://learn.unity.com/course/create-with-code';
const units = [
  ['getting-started', 'Getting Started'],
  ['unit-1-driving-simulation', 'Unit 1 - Player Control'],
  ['unit-2-basic-gameplay', 'Unit 2 - Basic Gameplay'],
  ['unit-3-sound-and-effects', 'Unit 3 - Sound and Effects'],
  ['unit-4-gameplay-mechanics', 'Unit 4 - Gameplay Mechanics'],
  ['unit-5-user-interface', 'Unit 5 - User Interface'],
  ['next-steps', 'Next Steps'],
] as const;
type Point = [title: string, text: string, section: string];

function chapter(unit: number, id: string, number: string, title: string, slug: string, points: Point[], note?: string): CourseChapter {
  const kind = id.startsWith('quiz-') ? 'quiz' : 'tutorial';
  return {
    id, number, title, originalTitle: units[unit][1],
    source: `${courseRoot}/unit/${units[unit][0]}/${kind}/${slug}?version=6.0`,
    sourceLabel: 'Unity 官方教程 · Unity 6.0 · 原小节编号',
    points: points.map(([title, text, source]) => ({ title, text, source })),
    ...(note ? { note } : {}),
  };
}

